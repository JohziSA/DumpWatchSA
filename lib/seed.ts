import { LOCAL_AUTHOR_ID, type EmojiReaction, type Report } from './types';

function iso(daysAgo: number, hour: number, minute: number): string {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

function pack(
  car: string,
  person?: string,
  plate?: string,
): Pick<Report, 'photos' | 'photoCar' | 'photoPerson' | 'photoPlate'> {
  const photos = [car, person, plate].filter(Boolean) as string[];
  return {
    photos,
    photoCar: car,
    photoPerson: person,
    photoPlate: plate,
  };
}

function emojis(items: [string, number][]): EmojiReaction[] {
  return items.map(([emoji, count]) => ({ emoji, count, mine: false }));
}

